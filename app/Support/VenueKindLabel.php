<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Человекочитаемая подпись типа площадки (`venues.kind`) для страницы места.
 *
 * В базе `kind` — не код, а готовая категория фильтра каталога: парсер пишет
 * туда одну из пяти строк VenueKindInference::KINDS («Сцены», «Клубы и бары»,
 * «Музеи», «Парки», «Пространства»), и фронт рисует их чипами как есть. Во
 * множественном числе они читаются как раздел каталога, а под названием
 * конкретного места нужен единственный: «Музей», а не «Музеи».
 *
 * Отдельно держим англоязычный словарь из комментария миграции venues
 * (theatre/club/museum/cafe/park) — так тип задумывался до появления
 * инференса, и старые строки могли остаться с этими значениями.
 *
 * Неизвестный тип возвращает null — сознательно. Заглушка «Площадка» под
 * названием площадки не несёт ни одного факта: для поисковика это шум, для
 * человека — пустая строка. Лучше не показать блок вовсе.
 */
final class VenueKindLabel
{
    /** @var array<string, string> нормализованный kind => подпись в единственном числе */
    private const LABELS = [
        // канонические категории каталога (VenueKindInference::KINDS в парсере)
        'сцены' => 'Сцена',
        'клубы и бары' => 'Клуб или бар',
        'музеи' => 'Музей',
        'парки' => 'Парк',
        'пространства' => 'Пространство',

        // словарь из комментария миграции create_venues_table
        'theatre' => 'Театр',
        'club' => 'Клуб',
        'museum' => 'Музей',
        'cafe' => 'Кафе',
        'park' => 'Парк',
    ];

    public static function for(?string $kind): ?string
    {
        $key = mb_strtolower(trim((string) $kind), 'UTF-8');

        return self::LABELS[$key] ?? null;
    }
}
