<?php

declare(strict_types=1);

namespace App\Support\Telegram;

/**
 * Имя площадки без мусора источника — одно на все посты канала.
 *
 * ЗАЧЕМ ОБЩЕЕ. Правило жило внутри подборки (BroadcastDigestComposer), а пост
 * ленты имя площадки не печатал вовсе. Когда лента научилась его печатать,
 * в одном канале оказалось бы два разных качества одной и той же строки:
 * подборка «Новый театр», пост ленты «Новый театр | Воронеж».
 *
 * ЧТО ЧИСТИМ. Афиши складывают в одно поле два названия одного места
 * («Arena Hall / Aura Night Club») и приклеивают город через трубу
 * («Новый театр | Воронеж»). В строке места это самое заметное место поста.
 *
 * ПОЧЕМУ ОТРЕЗАЕМ ТОЛЬКО С ТРЁХ СИМВОЛОВ. Отметка в начале строки — не
 * разделитель двух имён, а часть имени: «V | Concert Hall» после наивной
 * резки превратилось бы в «V».
 */
final class VenueName
{
    /** Разделители, после которых идёт второе имя или город. */
    private const MARKS = [' | ', ' / ', ' — филиал'];

    /** Отступ от начала, ближе которого разделитель считается частью имени. */
    private const MIN_HEAD = 3;

    public static function label(?string $raw): string
    {
        $name = trim((string) $raw);
        if ($name === '') {
            return '';
        }

        foreach (self::MARKS as $mark) {
            $at = mb_strpos($name, $mark);
            if ($at !== false && $at >= self::MIN_HEAD) {
                $name = trim(mb_substr($name, 0, $at));
            }
        }

        return $name;
    }
}
