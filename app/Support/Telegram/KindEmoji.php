        'yoga-wellness' => '🧘',
        'city' => '🏛️',
        // Широкие темы.
        'education' => '🎓',
        'music' => '🎵',
    ];

    /**
     * Слова, при которых значок этой темы в посте ЛИШНИЙ.
     *
     * «Спектакль „Весы“ 🎭» — значок пересказывает первое слово названия. Из
     * 449 предстоящих событий значок повторял слово названия у 135 (30%), а
     * добавлял тему у 307. Разбор пятью углами сошёлся на том, что повторяющий
     * знак — украшение: он не сообщает ничего и при этом тратит единственный
     * слот у названия, где мог бы стоять знак со смыслом.
     *
     * Стемы сверяются с границей слова слева (см. `titleNamesTheme`): без неё
     * «лекци» находится внутри «коллекция», «рок» — внутри «урок» и «барокко».
     * На этом уже спотыкался замер.
     */
    private const THEME_SAID_IN_TITLE = [
        '🎭' => ['спектакл', 'театр', 'моноспектакл'],
        '🎵' => ['концерт', 'музык', 'оркестр', 'квартирник'],
        '🎷' => ['джаз'],
