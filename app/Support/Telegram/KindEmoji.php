/**
 * Значок темы события — одна лестница на пост ленты и на строку подборки.
 *
 * Жила приватной в EventCaptionBuilder. Подборке понадобилась та же карта, но
 * с одним отличием, и отличие принципиальное.
 *
 * ПОДАВЛЕНИЕ «тема названа словом» нужно посту события и вредно подборке.
 * В посте значок стоит вплотную к названию, и «Спектакль „Весы“ 🎭» — повтор
 * первого слова: замер по 449 предстоящим — значок дублировал заголовок у 135
 * (30%), а добавлял тему у 307.
 *
 * В подборке значок — столбец слева от пяти строк, и дыра в нём читается как
 * сбой вёрстки, а не как сдержанность. Замер 25.09.2026 по 465 будущим
 * событиям: с подавлением значка нет у 167 (36%), без него — у 12 (2,6%);
 * на ближайших выходных 73 из 152 против 5.
 *
 * Поэтому подавление — аргумент вызывающего, а не правило карты.
 */
final class KindEmoji
{
    /**
     * Тема интереса → значок.
     *
     * ПОРЯДОК ЗДЕСЬ НИ НА ЧТО НЕ ВЛИЯЕТ — выбор делает `rank` тэггера, см.
     * `interestEmoji`. Раньше влиял, и это было ошибкой: словарь решал за
     * тэггера и терял главную тему события. Группировка ниже оставлена только
     * для чтения глазами.
     *
     * Значки подобраны так, чтобы различаться в ленте на телефоне: 🎷 и 🎸
     * видно с первого взгляда. 🎶 (эстрада) отсюда убран и слит с 🎵: два
     * восьмых с флажком в строке заголовка на телефоне неразличимы, разница
     * жила только в словаре. По той же причине убран 🎙 (рэп): второй микрофон
     * рядом с 🎤 стендапа читался бы как стендап, а выпадал он ноль раз.
     *
     * У 🖼️ и 🏛️ дописан U+FE0F. Без него presentation у этих кодовых точек
     * текстовый, и часть клиентов рисует их чёрно-белыми рядом с цветными
     * 📍 и 💸 — столбец значков разъезжается по цвету.
     */
    private const INTEREST_EMOJI = [
