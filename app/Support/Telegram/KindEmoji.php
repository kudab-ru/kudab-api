        '🩰' => ['балет', 'опера', 'мюзикл', 'оперетт'],
        '🎤' => ['стендап', 'стенд-ап', 'открытый микрофон', 'камеди'],
        '🖼️' => ['выставк', 'экспозиц', 'вернисаж'],
        '🎬' => ['кинопоказ', 'киносеанс', 'кинопремьер', 'кинофестивал'],
