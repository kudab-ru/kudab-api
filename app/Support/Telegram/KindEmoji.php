        '🎓' => ['лекци', 'семинар', 'лекторий', 'мастер-класс', 'мастер класс', 'мастерск'],
        '📖' => ['поэтическ', 'поэзи', 'литератур', 'книжн'],
        '🏃' => ['забег', 'марафон', 'турнир', 'чемпионат'],
        '🧸' => ['детск', 'для детей', 'малыш'],
        '🪩' => ['вечеринк', 'дискотек'],
        '🎪' => ['цирк'],
        '🎊' => ['фестивал'],
        '🎨' => ['мастер-класс', 'мастер класс'],
    ];

    /** Подвиды темы `music`: только они могут её вытеснить. */
    private const MUSIC_GENRES = [
        'jazz' => true,
        'rock' => true,
        'classical' => true,
        'opera-ballet' => true,
        'electronic' => true,
        'pop' => true,
    ];

    /**
     * Эмодзи по теме события — как у московского агрегатора, где значок
     * поддерживает название («Фонтаны на ВДНХ ⛲»).
     *
     * ГЛАВНЫЙ СИГНАЛ — ИНТЕРЕСЫ, а не слова в названии. Словарь по названию
     * стоял первым и покрывал 209 событий из 400: «Побег из тюрьмы» и
     * «Припять 36» — квесты, но слова «квест» в названии нет, и полторы сотни
     * постов уходили без значка. Интересы проставлены у 439 событий из 449,
     * справочник курируется руками, и тема в нём названа прямо.
     *
     * Внутри интересов побеждает УЗКИЙ над широким: у события часто стоят
     * сразу `music` и `jazz`, и 🎷 говорит больше, чем 🎵. Слова названия и
     * content_kind остались запасными путями — для тех десяти событий, что
     * пришли без тем вовсе.
     *
     * Незнакомая тема остаётся БЕЗ значка — лучше пусто, чем случайный:
     * ✨ у панихиды читается издевательством.
     *
     * @param  array<string, mixed>  $raw
     */
    public static function for(array $raw, bool $suppressWhenTitleSaysIt = true): string
    {
        $title = mb_strtolower((string) ($raw['title'] ?? $raw['name'] ?? ''));

        $byInterest = self::interestEmoji($raw['interest_slugs'] ?? null);
        if ($byInterest !== '') {
            return $suppressWhenTitleSaysIt && self::titleNamesTheme($title, $byInterest) ? '' : $byInterest;
        }

        $byWord = [
            '🎭' => ['спектакл', 'театр', 'моноспектакл', 'премьер'],
            '🎵' => ['концерт', 'джаз', 'рок-', 'симфон', 'оркестр', 'квартирник'],
            '🎤' => ['стендап', 'открытый микрофон', 'караоке'],
            '🖼️' => ['выставк', 'экспозиц', 'галере', 'вернисаж'],
            '🎬' => ['кинопоказ', 'киноклуб', 'фильм', 'кино'],
            '🧩' => ['квест', 'игротек', 'настолк', 'квиз'],
            '🏃' => ['забег', 'марафон', 'турнир', 'матч', 'чемпионат'],
            '🛍' => ['маркет', 'ярмарк', 'барахолк', 'своп'],
            '🚶' => ['экскурс', 'прогулк'],
            '🧸' => ['для детей', 'детск', 'малыш'],
            '🎓' => ['лекци', 'дискусс', 'мастер-класс'],
        ];

        foreach ($byWord as $emoji => $words) {
            foreach ($words as $word) {
                if ($word !== '' && mb_strpos($title, $word) !== false) {
                    return $emoji;
                }
            }
        }

        return match ((string) ($raw['content_kind'] ?? '')) {
            'culture' => '🎭',
            'education' => '🎓',
            'sport' => '🏃',
            'civic' => '🏛️',
            default => '',
        };
    }

    /**
     * Название уже называет эту тему словом?
     *
     * Граница слова проверяется только СЛЕВА: русские окончания меняют хвост
     * стема («экскурсия», «экскурсию», «экскурсионный»), а приставки и
     * вхождение внутрь слова — это как раз ложные срабатывания, от которых
     * защищаемся.
     */
    private static function titleNamesTheme(string $lowerTitle, string $emoji): bool
    {
        foreach (self::THEME_SAID_IN_TITLE[$emoji] ?? [] as $stem) {
            if (preg_match('~(?<![а-яёa-z])'.preg_quote($stem, '~').'~u', $lowerTitle) === 1) {
                return true;
            }
        }

        return false;
    }

    /**
     * Значок по темам события.
     *
     * ПОРЯДОК ЗАДАЁТ ТЭГГЕР, А НЕ ЭТОТ СЛОВАРЬ. Слаги приходят в порядке
     * `rank`: нулевой — главная тема. Первая версия перебирала словарь, а не
     * темы события, и главную тему теряла: «Экскурсия „Вселенная театра“» с
     * темами excursions(r0), theatre(r1) получала 🎭, «Ток-шоу» с
     * education(r0), quiz-games(r1) — 🧩, «Корпорация Монстров» с
     * quiz-games(r0), cinema(r1) — 🎬. Из 77 названий, где тема прямо названа
     * словом, значок противоречил названию у 21. Тэггер при этом был прав:
     * главная тема совпадала с названием во всех этих случаях.
     *
     * Единственное исключение — музыкальные жанры. `music` это НАДТЕМА джаза и
     * рока, и 🎷 говорит больше, чем 🎵. Для прочих пар такого отношения нет:
     * `quiz-games` не подвид `education`, и подменять одно другим значит
     * возвращать ту же ошибку.
     *
     * @param  mixed  $slugs  слаги в порядке rank: нулевой — главная тема
     */
    private static function interestEmoji(mixed $slugs): string
    {
        if (! is_array($slugs)) {
            return '';
        }

        $ordered = [];
        foreach ($slugs as $slug) {
            if (is_string($slug) && trim($slug) !== '') {
                $ordered[] = mb_strtolower(trim($slug));
            }
        }

        foreach ($ordered as $slug) {
            $emoji = self::INTEREST_EMOJI[$slug] ?? null;
            if ($emoji === null) {
                continue;
            }

            if ($slug === 'music') {
                foreach ($ordered as $other) {
                    // Значок жанра проверяем отдельно от списка жанров: жанр
                    // без значка (такое уже было у hip-hop) иначе вернул бы
                    // null там, где обещана строка.
                    $genre = self::INTEREST_EMOJI[$other] ?? '';
                    if ($genre !== '' && isset(self::MUSIC_GENRES[$other])) {
                        return $genre;
                    }
                }
            }

            return $emoji;
        }

        return '';
    }
}
